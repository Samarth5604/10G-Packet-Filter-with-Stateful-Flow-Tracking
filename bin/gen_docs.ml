(* gen_docs.ml -- fifth backend: documentation.
   Hand-written protocol docs drift from the spec within a week. These do not:
   every offset, bound and bin below is computed from [Protocol_spec.stack] at
   build time. Regenerate in CI and fail on diff. *)

open Protocol_spec

let buf = Buffer.create 8192
let p fmt = Printf.ksprintf (Buffer.add_string buf) fmt

let action_str = function
  | Drop -> "drop"
  | Forward_unclassified -> "forward unclassified"

let values_str = function
  | Any -> "any"
  | Range (lo, hi) -> Printf.sprintf "%d..%d" lo hi
  | One_of vs -> "{" ^ String.concat "," (List.map string_of_int vs) ^ "}"
  | Derived -> "_derived_"

let length_str = function
  | Fixed n -> Printf.sprintf "fixed %d B" n
  | From_field { lf_field; scale } -> Printf.sprintf "`%s` x %d B" lf_field scale

let emit st =
  p "<!-- GENERATED by gen_docs.ml from lib/protocol_spec.ml. DO NOT EDIT. -->\n";
  p "# Parsed protocol stack\n\n";

  p "## Derived bounds\n\n";
  p "These are computed from the spec, not chosen by hand. The generated RTL \
     pipeline depth, the golden model, the stimulus generator and the coverage \
     bins all consume the same values, so they cannot disagree.\n\n";
  p "| quantity | value | consumed by |\n|---|---|---|\n";
  p "| worst-case parse window | %d B (budget %d B) | cut-through threshold |\n"
    (max_parse_bytes st) st.parse_window_bytes;
  p "| cut-through delay | %d beats @ 64-bit | egress commit point |\n"
    (cut_through_beats ~datapath_bits:64 st);
  p "| flow key width | %d bits | URAM table geometry |\n" (export_bits st);
  p "| unparseable action | %s | drop counters |\n\n"
    (action_str st.on_unparseable);

  p "The parse window is **asserted** in the spec and checked by `validate`. \
     Widening the stack past the budget fails the build rather than silently \
     costing latency.\n\n";

  p "## Layer graph\n\n```mermaid\ngraph LR\n";
  List.iter
    (fun l ->
       match l.next with
       | Payload -> p "  %s --> PAYLOAD\n" l.lname
       | Switch { sw_field; cases; default; require } ->
         List.iter
           (fun (v, nxt) -> p "  %s -->|%s=0x%X| %s\n" l.lname sw_field v nxt)
           cases;
         (match default with
          | Some d -> p "  %s -->|default| %s\n" l.lname d
          | None -> p "  %s -->|else| UNPARSEABLE\n" l.lname);
         List.iter
           (fun g -> p "  %s -->|!%s| UNPARSEABLE\n" l.lname g.g_reason)
           require)
    st.layers;
  p "```\n\n";

  p "## Layers\n\n";
  List.iter
    (fun l ->
       p "### `%s`\n\n" l.lname;
       p "span %s &middot; max repeats %d" (length_str l.length) l.max_repeats;
       if l.exports <> [] then
         p " &middot; exports `%s`" (String.concat "`, `" l.exports);
       p "\n\nread depth for classification: **%d B**\n\n" (layer_read_bytes l);
       p "| field | bit offset | width | accepted values | role |\n";
       p "|---|---|---|---|---|\n";
       List.iter
         (fun f ->
            let role = ref [] in
            if List.mem f.fname l.exports then role := "key" :: !role;
            (match l.length with
             | From_field { lf_field; _ } when lf_field = f.fname ->
               role := "length" :: !role
             | _ -> ());
            (match l.next with
             | Switch { sw_field; require; _ } ->
               if sw_field = f.fname then role := "selector" :: !role;
               List.iter
                 (fun g ->
                    if g.g_field = f.fname then role := "guard" :: !role)
                 require
             | Payload -> ());
            p "| `%s` | %d | %d | %s | %s |\n" f.fname (field_offset l f.fname)
              f.width (values_str f.values)
              (match !role with [] -> "&mdash;" | r -> String.concat ", " r))
         l.fields;
       p "\n";
       match l.next with
       | Switch { require; _ } when require <> [] ->
         p "**Guards.** The next layer exists only if all hold; otherwise the \
            frame is unparseable and a per-reason counter increments.\n\n";
         List.iter
           (fun g ->
              p "- `%s` &isin; %s &mdash; else `%s` (read depth %d B)\n"
                g.g_field (values_str g.g_values) g.g_reason
                ((field_end l g.g_field + 7) / 8))
           require;
         p "\n"
       | _ -> ())
    st.layers;

  p "## Coverage bins\n\n";
  p "Derived by enumerating selector cases, guard outcomes and repeat depths.\n\n";
  let n = ref 0 in
  List.iter
    (fun l ->
       match l.next with
       | Payload -> ()
       | Switch { sw_field; cases; require; _ } ->
         List.iter
           (fun (v, nxt) ->
              incr n;
              p "- `%s.%s == 0x%X` -> `%s`\n" l.lname sw_field v nxt)
           cases;
         incr n;
         p "- `%s.%s` unmatched -> unparseable\n" l.lname sw_field;
         List.iter
           (fun g ->
              n := !n + 2;
              p "- `%s` pass / fail\n" g.g_reason)
           require;
         if l.max_repeats > 1 then
           for d = 1 to l.max_repeats do
             incr n;
             p "- `%s` at depth %d\n" l.lname d
           done)
    st.layers;
  p "\n**%d bins total.**\n" !n

(* Writes to stdout: the caller redirects. Keeps the generator free of any
   assumption about the build sandbox's working directory. *)
let () =
  validate stack;
  emit stack;
  print_string (Buffer.contents buf)
